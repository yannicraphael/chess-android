// Theory for the opening trainer: why the moves are played, the plans after the opening,
// the pawn structure, typical traps and what to do when the opponent leaves the book.
// `notes[line][ply]` explains every move of every line (same order as OPENINGS[].lines).
// Moves are English SAN; the app shows them in German notation.

export interface Deviation {
  after: string // moves before the deviation (English SAN, from the start)
  move: string // the opponent's deviation
  answer: string // your recommended reply
  why: string
}

export interface OpeningTheory {
  plans: string[] // your plans in the middlegame
  structure: string // pawn structure and what it means
  watch: string[] // what the opponent wants, what to look out for
  deviations: Deviation[]
  traps: string[]
  lineIdeas: string[] // one per line: what this variation is about
  notes: string[][] // one string per ply for every line
}

